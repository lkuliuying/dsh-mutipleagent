const DICT = { zh, en };
const warnKey = key => !warnedKeys.has(key) && warnedKeys.add(key);
const warnedKeys = new Set();
const listeners = new Set();
let current = null;

function detectLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch {
    /* 无存储权限时按浏览器语言判断 */
  }
  const tag = typeof navigator !== 'undefined' && typeof navigator.language === 'string' ? navigator.language : '';
  if (!tag) return 'zh';
  return tag.toLowerCase().split('-')[0] === 'zh' ? 'zh' : 'en';
}

export function getLang() {
  if (!current) current = detectLang();
  return current;
}

function interpolate(text, params) {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match));
}

function warnMissing(key, lang) {
  if (!warnKey(lang + ':' + key)) return;
  console.warn('[i18n] missing "' + key + '" for "' + lang + '", falling back to Chinese');
}

export function hasKey(key) {
  return Object.prototype.hasOwnProperty.call(zh, key) || Object.prototype.hasOwnProperty.call(en, key);
}

export function t(key, params) {
  const lang = getLang();
  const table = DICT[lang] || zh;
  let text = table[key];
  if (text == null) {
    warnMissing(key, lang);
    text = zh[key];
  }
  return text == null ? String(key) : interpolate(text, params);
}

export function locale() {
  return getLang() === 'zh' ? 'zh-CN' : 'en-US';
}

export function statusText(status) {
  return hasKey('status.' + status) ? t('status.' + status) : t('status.unknown');
}

export function eventText(type) {
  return hasKey('event.' + type) ? t('event.' + type) : String(type || '');
}

// 把带 data-i18n* 属性的静态节点就地翻译；切换语言后会再次调用。
export function applyStatic(root = typeof document !== 'undefined' ? document : null) {
  if (!root || typeof root.querySelectorAll !== 'function') return;
  for (const el of root.querySelectorAll('[data-i18n]')) {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.title = t(key);
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.placeholder = t(key);
  }
  for (const el of root.querySelectorAll('[data-i18n-aria-label]')) {
    const key = el.getAttribute('data-i18n-aria-label');
    if (key) el.setAttribute('aria-label', t(key));
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = getLang() === 'zh' ? 'zh-CN' : 'en';
  }
}

export function onLangChange(cb) {
  if (typeof cb !== 'function') return () => {};
  listeners.add(cb);
  return () => listeners.delete(cb);
}

export function setLang(next) {
  const value = LANGS.includes(next) ? next : getLang();
  const changed = value !== getLang();
  current = value;
  try {
    localStorage.setItem(STORAGE_KEY, value);
  } catch {
    /* 无法持久化时仍在本页生效 */
  }
  applyStatic();
  for (const el of document.querySelectorAll('button[data-lang]')) el.setAttribute('aria-pressed', String(el.dataset.lang === value));
  if (!changed) return value;
  for (const cb of [...listeners]) {
    try {
      cb(value);
    } catch (error) {
      console.error('[i18n] language listener failed', error);
    }
  }
  return value;
}

// 绑定页面右上角的中 / EN 切换按钮，返回解绑函数。
export function mountLangSwitch(root = typeof document !== 'undefined' ? document : null) {
  if (!root || typeof root.querySelectorAll !== 'function') return () => {};
  const buttons = [...root.querySelectorAll('button[data-lang]')];
  const sync = () => {
    const lang = getLang();
    for (const el of buttons) {
      const active = el.dataset.lang === lang;
      el.setAttribute('aria-pressed', String(active));
      el.classList.toggle('active', active);
    }
  };
  const onClick = event => {
    const button = event.target.closest('button[data-lang]');
    if (!button) return;
    event.preventDefault();
    setLang(button.dataset.lang);
    sync();
  };
  for (const el of root.querySelectorAll('[data-lang-switch]')) el.addEventListener('click', onClick);
  const off = onLangChange(() => {
    applyStatic();
    sync();
  });
  sync();
  return () => {
    off();
    for (const el of root.querySelectorAll('[data-lang-switch]')) el.removeEventListener('click', onClick);
  };
}

// 页面加载时立即按已保存（或浏览器）语言应用静态文案；模块脚本在解析后执行。
if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => applyStatic());
  else applyStatic();
}
